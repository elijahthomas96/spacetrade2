using System.Collections.Generic;
using System.Linq;
using SpaceTrade.Sim.Json;

namespace SpaceTrade.Sim.Tuning
{
    /// <summary>Writes tuning data as JSON in the same layout and field order the reader expects.</summary>
    public static class TuningWriter
    {
        public static string Write(TuningData t)
        {
            var root = new JsonObjectBuilder()
                .Add("start", new JsonObjectBuilder()
                    .Add("startingCredits", t.Start.StartingCredits)
                    .Add("starterShipClass", t.Start.StarterShipClass)
                    .Add("starterDrive", t.Start.StarterDrive)
                    .Add("openingOffers", new JsonObjectBuilder()
                        .Add("minFeasibleJobs", t.Start.OpeningOffers.MinFeasibleJobs)
                        .Add("minProfitableJobs", t.Start.OpeningOffers.MinProfitableJobs))
                    .Add("marketStartFill", new JsonObjectBuilder()
                        .Add("supplyPercent", t.Start.MarketStartFill.SupplyPercent)
                        .Add("demandPercent", t.Start.MarketStartFill.DemandPercent)
                        .Add("passengerPercent", t.Start.MarketStartFill.PassengerPercent)))
                .Add("galaxy", new JsonObjectBuilder()
                    .Add("systemCountMin", t.Galaxy.SystemCountMin)
                    .Add("systemCountMax", t.Galaxy.SystemCountMax)
                    .Add("nearestNeighbourMinMilliLy", t.Galaxy.NearestNeighbourMinMilliLy)
                    .Add("nearestNeighbourMaxMilliLy", t.Galaxy.NearestNeighbourMaxMilliLy)
                    .Add("maxHopMilliLy", t.Galaxy.MaxHopMilliLy)
                    .Add("industriesPerSystemMin", t.Galaxy.IndustriesPerSystemMin)
                    .Add("industriesPerSystemMax", t.Galaxy.IndustriesPerSystemMax)
                    .Add("shipyardCountMin", t.Galaxy.ShipyardCountMin)
                    .Add("shipyardCountMax", t.Galaxy.ShipyardCountMax)
                    .Add("populationMinMillions", t.Galaxy.PopulationMinMillions)
                    .Add("populationMaxMillions", t.Galaxy.PopulationMaxMillions)
                    .Add("names", t.Galaxy.Names, onePerLine: true))
                .Add("industries", Each(t.Industries, i => new JsonObjectBuilder()
                    .Add("id", i.Id)
                    .Add("name", i.Name)
                    .Add("consumes", i.Consumes)
                    .Add("produces", i.Produces)
                    .Add("producesPassengers", i.ProducesPassengers)
                    .Add("enablesShipyard", i.EnablesShipyard)))
                .Add("commodities", Each(t.Commodities, c => new JsonObjectBuilder()
                    .Add("id", c.Id)
                    .Add("name", c.Name)
                    .Add("baseRatePerTonne", c.BaseRatePerTonne)
                    .Add("rateRollMinPercent", c.RateRollMinPercent)
                    .Add("rateRollMaxPercent", c.RateRollMaxPercent)
                    .Add("supplyCapTonnes", c.SupplyCapTonnes)
                    .Add("demandCapTonnes", c.DemandCapTonnes)
                    .Add("supplyReplenishTonnes", c.SupplyReplenishTonnes)
                    .Add("demandReplenishTonnes", c.DemandReplenishTonnes)
                    .Add("replenishIntervalDays", c.ReplenishIntervalDays)))
                .Add("passengers", new JsonObjectBuilder()
                    .Add("baseFare", t.Passengers.BaseFare)
                    .Add("fareRollMinPercent", t.Passengers.FareRollMinPercent)
                    .Add("fareRollMaxPercent", t.Passengers.FareRollMaxPercent)
                    .Add("poolCapBasePassengers", t.Passengers.PoolCapBasePassengers)
                    .Add("poolCapExtraPerTenMillionPopulation", t.Passengers.PoolCapExtraPerTenMillionPopulation)
                    .Add("hubPoolBonusPercent", t.Passengers.HubPoolBonusPercent)
                    .Add("replenishPassengers", t.Passengers.ReplenishPassengers)
                    .Add("replenishIntervalDays", t.Passengers.ReplenishIntervalDays))
                .Add("rates", new JsonObjectBuilder()
                    .Add("distanceFactorBasePercent", t.Rates.DistanceFactorBasePercent)
                    .Add("distanceFactorPerLyPercent", t.Rates.DistanceFactorPerLyPercent)
                    .Add("rerollIntervalDays", t.Rates.RerollIntervalDays))
                .Add("provisions", new JsonObjectBuilder()
                    .Add("fuelBasePricePerTonne", t.Provisions.FuelBasePricePerTonne)
                    .Add("foodBasePricePerTonne", t.Provisions.FoodBasePricePerTonne)
                    .Add("waterBasePricePerTonne", t.Provisions.WaterBasePricePerTonne)
                    .Add("priceRollMinPercent", t.Provisions.PriceRollMinPercent)
                    .Add("priceRollMaxPercent", t.Provisions.PriceRollMaxPercent)
                    .Add("industryModifiers", Each(t.Provisions.IndustryModifiers, m => new JsonObjectBuilder()
                        .Add("industry", m.Industry)
                        .Add("fuelPercent", m.FuelPercent)
                        .Add("foodPercent", m.FoodPercent)
                        .Add("waterPercent", m.WaterPercent)))
                    .Add("combinedModifierMinPercent", t.Provisions.CombinedModifierMinPercent)
                    .Add("combinedModifierMaxPercent", t.Provisions.CombinedModifierMaxPercent)
                    .Add("foodGramsPerPersonPerDay", t.Provisions.FoodGramsPerPersonPerDay)
                    .Add("waterGramsPerPersonPerDay", t.Provisions.WaterGramsPerPersonPerDay)
                    .Add("personMassKg", t.Provisions.PersonMassKg))
                .Add("ships", Each(t.Ships, s => new JsonObjectBuilder()
                    .Add("id", s.Id)
                    .Add("name", s.Name)
                    .Add("dryMassTonnes", s.DryMassTonnes)
                    .Add("holdTonnes", s.HoldTonnes)
                    .Add("tankTonnes", s.TankTonnes)
                    .Add("berths", s.Berths)
                    .Add("crew", s.Crew)
                    .Add("price", s.Price)
                    .Add("inSystemDailyIncome", s.InSystemDailyIncome)))
                .Add("shipNames", t.ShipNames, onePerLine: true)
                .Add("drives", Each(t.Drives, d => new JsonObjectBuilder()
                    .Add("id", d.Id)
                    .Add("name", d.Name)
                    .Add("speedMilliC", d.SpeedMilliC)
                    .Add("price", d.Price)
                    .Add("fuelKgPerTonneLy", d.FuelKgPerTonneLy)))
                .Add("shipyards", new JsonObjectBuilder()
                    .Add("shipStockPerClassMin", t.Shipyards.ShipStockPerClassMin)
                    .Add("shipStockPerClassMax", t.Shipyards.ShipStockPerClassMax)
                    .Add("driveStockPerTierMin", t.Shipyards.DriveStockPerTierMin)
                    .Add("driveStockPerTierMax", t.Shipyards.DriveStockPerTierMax)
                    .Add("restockIntervalDays", t.Shipyards.RestockIntervalDays)
                    .Add("restockAmount", t.Shipyards.RestockAmount)
                    .Add("priceRollMinPercent", t.Shipyards.PriceRollMinPercent)
                    .Add("priceRollMaxPercent", t.Shipyards.PriceRollMaxPercent))
                .Add("automation", new JsonObjectBuilder()
                    .Add("recheckMinIntervalDays", t.Automation.RecheckMinIntervalDays))
                .Add("notifications", new JsonObjectBuilder()
                    .Add("keepNewest", t.Notifications.KeepNewest))
                .Add("receipts", new JsonObjectBuilder()
                    .Add("keepNewest", t.Receipts.KeepNewest));
            return root.ToString();
        }

        private static List<JsonObjectBuilder> Each<T>(IEnumerable<T> items, System.Func<T, JsonObjectBuilder> build) => items.Select(build).ToList();
    }
}
